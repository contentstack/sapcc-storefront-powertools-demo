#!/usr/bin/env node
/**
 * Generates src/environments/contentstack.environment.ts from environment
 * variables. Runs automatically before `npm start` / `npm run build` (see the
 * "prestart"/"prebuild" scripts in package.json) so credentials never need to
 * live in a committed source file.
 *
 * Local dev: put real values in a gitignored `.env` file (copy `.env.example`).
 * Deploy: set the same variables in your hosting platform's env var settings —
 * no `.env` file needed there, this script reads `process.env` either way.
 */
require('dotenv').config();

const fs = require('fs');
const path = require('path');

const VALID_REGIONS = ['US', 'EU', 'AZURE_NA', 'AZURE_EU', 'GCP_NA', 'GCP_EU'];

const required = ['CS_API_KEY', 'CS_DELIVERY_TOKEN'];
const missing = required.filter((k) => !process.env[k]);
if (missing.length) {
  console.error(`[contentstack-env] Missing required env var(s): ${missing.join(', ')}`);
  console.error('[contentstack-env] Set them in a local .env file (see .env.example) or your host\'s env var settings.');
  process.exit(1);
}

const region = process.env.CS_REGION || 'US';
if (!VALID_REGIONS.includes(region)) {
  console.error(`[contentstack-env] CS_REGION="${region}" is not valid. Must be one of: ${VALID_REGIONS.join(', ')}`);
  process.exit(1);
}

const environment = process.env.CS_ENVIRONMENT || 'development';
const livePreview = process.env.CS_LIVE_PREVIEW === 'true';

const content = `import { Region } from '@contentstack/delivery-sdk';

// AUTO-GENERATED by scripts/generate-contentstack-env.js — do not edit by hand,
// your changes will be overwritten on the next build. Edit .env instead.
export const contentstackDelivery = {
  apiKey: '${process.env.CS_API_KEY}',
  deliveryToken: '${process.env.CS_DELIVERY_TOKEN}',
  environment: '${environment}',
  region: Region.${region},
  livePreview: ${livePreview},
};
`;

const outPath = path.join(__dirname, '..', 'src', 'environments', 'contentstack.environment.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`[contentstack-env] Wrote ${outPath} (region=${region}, environment=${environment}, livePreview=${livePreview})`);
